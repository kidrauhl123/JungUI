export type ThemeToggleProps = Omit<
  ComponentProps<"button">,
  "onChange" | "value" | "defaultValue"
> & {
  value?: "light" | "dark";
  defaultValue?: "light" | "dark";
  onValueChange?: (theme: "light" | "dark") => void;
};
export function ThemeToggle({
  value,
  defaultValue = "light",
  onValueChange,
  className,
  onClick,
  ...props
}: ThemeToggleProps) {
  const [internal, setInternal] = useState(defaultValue);
  const dark = (value ?? internal) === "dark";
  return (
    <button
      type="button"
      aria-label="切换主题"
      {...props}
      data-slot="theme-toggle"
      data-theme={dark ? "dark" : "light"}
      className={cn("jui-theme-toggle", className)}
      aria-pressed={dark}
      onClick={(event) => {
        onClick?.(event);
        if (event.defaultPrevented) return;
        const next = dark ? "light" : "dark";
        if (value === undefined) setInternal(next);
        onValueChange?.(next);
      }}
    >
      <svg
        className="tt-icon tt-sun"
        viewBox="0 0 24 24"
        fill="none"
        aria-hidden="true"
      >
        <path
          fillRule="evenodd"
          clipRule="evenodd"
          d={SUN_RING}
          fill="currentColor"
        />
        <path d={SUN_RAYS} fill="currentColor" />
      </svg>
      <svg
        className="tt-icon tt-moon"
        viewBox="0 0 24 24"
        fill="none"
        aria-hidden="true"
      >
        <path d={MOON} fill="currentColor" />
      </svg>
    </button>
  );
}
